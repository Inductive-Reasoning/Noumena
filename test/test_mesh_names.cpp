std::unique_ptr<mfem::Mesh> Load(const std::string& text) {
	std::istringstream input(text);
	return mesh_io::LoadMesh(input);
}

std::set<int> Set(const mfem::AttributeSets& sets, const std::string& name) {
	REQUIRE(sets.AttributeSetExists(name));
	const mfem::Array<int>& ids = sets.GetAttributeSet(name);
	return std::set<int>(ids.begin(), ids.end());
}

